#!/usr/bin/env python3
"""Genera HTTP bootstrap o HTTPS según los certificados realmente disponibles."""
import os
from pathlib import Path
from registry import ROOT, sites


def render(row, tls):
    domain = row["domain"]
    names = " ".join([domain, *row["aliases"]])
    acme = """    location ^~ /.well-known/acme-challenge/ {
        root /var/www/certbot;
        default_type text/plain;
        try_files $uri =404;
    }
"""
    text = f"server {{\n    listen 80;\n    server_name {names};\n" + acme
    text += (f"    location / {{ return 301 https://{domain}$request_uri; }}\n" if tls
             else "    location / { return 503; }\n") + "}\n"
    if tls:
        text += f"""
server {{
    listen 443 ssl;
    server_name {names};
    ssl_certificate /etc/letsencrypt/live/{domain}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/{domain}/privkey.pem;
    add_header X-Content-Type-Options nosniff always;
    add_header Referrer-Policy strict-origin-when-cross-origin always;
    location ~ /\\.(?!well-known/) {{ return 404; }}
    location ~* \\.(sql|bak|log|ini)$ {{ return 404; }}
    location / {{
        # Variable + resolver: un backend ausente no impide arrancar el proxy.
        set $backend http://web-{row['id']}:80;
        proxy_pass $backend;
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Host $host;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header X-Forwarded-Port 443;
        proxy_connect_timeout 5s;
        proxy_read_timeout 120s;
    }}
}}
"""
    return text


def main():
    out = ROOT / "proxy/conf.d"
    out.mkdir(parents=True, exist_ok=True)
    certs = Path(os.environ.get("LETSENCRYPT_DIR", "/etc/letsencrypt"))
    # El host nunca modifica nginx.conf. Archivos temporales no terminan en .conf.
    configs = {"00-default.conf": "server { listen 80 default_server; server_name _; return 444; }\n"
               "server { listen 443 ssl default_server; ssl_reject_handshake on; }\n"}
    for row in sites():
        live = certs / "live" / row["domain"]
        tls = (live / "fullchain.pem").is_file() and (live / "privkey.pem").is_file()
        configs[row["id"] + ".conf"] = render(row, tls)
    marker = "# Generated by dockerws/scripts/render-proxy.py\n"
    for name, content in configs.items():
        temp = out / (".render-" + name)
        temp.write_text(marker + content)
        os.replace(temp, out / name)
    for path in out.glob("*.conf"):
        if path.name not in configs and path.read_text().startswith(marker):
            path.unlink()


if __name__ == "__main__":
    main()
